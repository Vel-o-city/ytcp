import { describe, expect, it } from "vitest";

import { type YouTubeTranscriptRecord } from "../../src/youtube/contracts.js";
import { normalizeTranscriptRecord } from "../../src/youtube/normalize.js";
import { parseYouTubeInput } from "../../src/youtube/parser.js";
import type { YouTubeVideoReference } from "../../src/youtube/reference.js";

function expectVideoReference(value: ReturnType<typeof parseYouTubeInput>): YouTubeVideoReference {
  expect(value.kind).toBe("video");

  if (value.kind !== "video") {
    throw new Error("Expected a video reference");
  }

  return value;
}

describe("youtube transcript normalization", () => {
  it("normalizes transcript segments and language metadata into a stable plain record", () => {
    const reference = expectVideoReference(
      parseYouTubeInput("https://www.youtube.com/watch?v=dQw4w9WgXcQ")
    );

    const record = normalizeTranscriptRecord(
      {
        languages: ["English", "Deutsch"],
        selectedLanguage: "English",
        transcript: {
          content: {
            body: {
              initial_segments: [
                {
                  start_ms: "0",
                  end_ms: "2200",
                  start_time_text: { text: "0:00" },
                  snippet: { text: "Hello world" }
                },
                {
                  start_ms: "2200",
                  end_ms: "4800",
                  start_time_text: { text: "0:02" },
                  snippet: { runs: [{ text: "Build " }, { text: "with MCP" }] }
                }
              ]
            }
          }
        }
      },
      reference,
      {
        basic_info: {
          title: "Transcript-ready video",
          channel: {
            name: "Example Dev"
          }
        },
        captions: {
          caption_tracks: [
            {
              name: { text: "English" },
              language_code: "en",
              kind: "asr",
              is_translatable: true
            },
            {
              name: { text: "Deutsch" },
              language_code: "de",
              is_translatable: true
            }
          ]
        }
      }
    );

    expect(record satisfies YouTubeTranscriptRecord).toBe(record);
    expect(record).toEqual({
      kind: "transcript",
      videoId: "dQw4w9WgXcQ",
      canonicalUrl: "https://www.youtube.com/watch?v=dQw4w9WgXcQ",
      source: "watch",
      title: "Transcript-ready video",
      channelTitle: "Example Dev",
      language: "English",
      languages: [
        {
          label: "English",
          languageCode: "en",
          isSelected: true,
          isAutoGenerated: true,
          isTranslatable: true
        },
        {
          label: "Deutsch",
          languageCode: "de",
          isSelected: false,
          isTranslatable: true
        }
      ],
      segmentCount: 2,
      segments: [
        {
          startMs: 0,
          endMs: 2200,
          startTimeSeconds: 0,
          endTimeSeconds: 2,
          startTimeText: "0:00",
          text: "Hello world"
        },
        {
          startMs: 2200,
          endMs: 4800,
          startTimeSeconds: 2,
          endTimeSeconds: 4,
          startTimeText: "0:02",
          text: "Build with MCP"
        }
      ],
      text: "Hello world\nBuild with MCP"
    });
  });

  it("drops malformed transcript rows and still exposes translation language metadata", () => {
    const reference = expectVideoReference(parseYouTubeInput("dQw4w9WgXcQ"));

    const record = normalizeTranscriptRecord(
      {
        languages: ["English", "Español"],
        selectedLanguage: "Español",
        transcript: {
          content: {
            body: {
              initial_segments: [
                {
                  title: "Section header"
                },
                {
                  start_ms: "5000",
                  end_ms: "8100",
                  start_time_text: { simpleText: "0:05" },
                  snippet: { simpleText: "Hola mundo" }
                }
              ]
            }
          }
        }
      },
      reference,
      {
        captions: {
          translation_languages: [
            {
              language_code: "es",
              language_name: { text: "Español" }
            }
          ]
        }
      }
    );

    expect(record.languages).toEqual([
      {
        label: "English",
        isSelected: false
      },
      {
        label: "Español",
        languageCode: "es",
        isSelected: true,
        isTranslatable: true
      }
    ]);
    expect(record.segmentCount).toBe(1);
    expect(record.segments).toEqual([
      {
        startMs: 5000,
        endMs: 8100,
        startTimeSeconds: 5,
        endTimeSeconds: 8,
        startTimeText: "0:05",
        text: "Hola mundo"
      }
    ]);
    expect(record.text).toBe("Hola mundo");
  });
});
